//! `several-definitions` and `many-definitions` (#107): a module holding more
//! top-level definitions than it should.
//!
//! ONE ladder, two rules, disjoint ranges — exactly one fires:
//!
//! - [`SEVERAL_MIN`] <= count < [`MANY_MIN`] fires `several-definitions`;
//! - count >= [`MANY_MIN`] fires `many-definitions`.
//!
//! Both languages are judged at both rungs. The definitions are counted
//! differently — a Rust class equivalent is a type plus the functions that take
//! it — but the ladder is the same ladder: the count is of concepts either way,
//! and a Rust module of three concepts is no more one module than a Python one
//! is.
//!
//! The ranges are stated as the constants' names, never as numerals: the two
//! values moved twice while the ladder was designed, and every prose copy that
//! spelled them out went stale (2026-11-18 review: one function's doc stated
//! the previous pair of ranges over the current ladder — the tool reads code
//! shape, not prose, so nothing caught it).
//!
//! The split exists so a repo can set its policy: disable
//! `several-definitions` and a Python module is judged only at the loose rung,
//! or keep it and hold Python modules to the strict one. Rust is judged at the
//! loose rung only — a class equivalent there is a type plus the functions that
//! take it, and that unit is the normal module.
//!
//! The message branches on what the definitions ARE. A module whose
//! definitions are mostly classes becomes a PACKAGE — one file per class
//! inside it, so the family keeps its name. A module whose definitions are
//! mostly free functions has no object to own the data they pass around, so
//! the reader names the domain concepts and makes them classes.
//!
//! Two exclusions: "all but one class are value records" is one class plus
//! its records, and a decorated function is registered with a caller outside
//! the module (a framework route, a CLI command) — a module made only of
//! those is a framework contract, not a module full of concepts.
//!
//! The measurement is in `docs/plans/plan-issue-107-module-shape.md`.

use ruff_python_ast::Stmt;

use crate::finding::Finding;

/// The fewest definitions that make a module `several-definitions`: a class, a
/// data table or a record may hold two, never three. Both languages — a Rust
/// class equivalent is a type plus the functions that take it, so the count is
/// of concepts either way.
///
/// The rungs' bounds are stated HERE and nowhere else; every other comment
/// cites them. A restated bound is a second copy, and the second copy is the
/// one that goes stale (2026-11-18 review). Each constant is the count at which
/// its rule STARTS, so both comparisons read `count >= MIN` and no reader has
/// to decide whether a bound is inclusive.
pub const SEVERAL_MIN: usize = 3;

/// The fewest definitions that make a module `many-definitions`, in both
/// languages: one above the last count the strict rung covers. Ten definitions
/// is the most one file may hold as one concept; eleven is the split.
pub const MANY_MIN: usize = 11;

/// The fewest free functions that make the functions arm's claim — "the data
/// the others share arrives as parameters" — true of the module. One helper
/// shares its data with nobody.
const FUNCTIONS_GROUP_MIN: usize = 2;

/// How many opening lines may carry a generator marker. Generators stamp the
/// top of the file; a marker further down is prose about something else.
const GENERATED_HEAD_LINES: usize = 20;

/// The markers a generator leaves at the top of a file it writes.
const GENERATED_MARKERS: &[&str] = &[
    "do not edit",
    "auto-generated",
    "autogenerated",
    "@generated",
    "generated by",
    "code generated",
];

/// The top-level directories whose modules run as programs: the reader of a
/// script is owed the "a script is not different" argument, because that is
/// where the objection comes from.
const SCRIPT_DIRS: &[&str] = &["scripts", "tools", "bin"];

/// The language the module is written in — the advice differs (a Python class
/// lives in a file, a Rust type in a module; a package has `__init__.py`, a
/// directory module does not).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Language {
    #[default]
    Python,
    Rust,
}

/// Which rung a module's definition count falls on. The two rungs are the two
/// rules, and a count belongs to exactly one — see `ModuleShape::rung`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Rung {
    /// Above the strict floor, below the loose one — both languages.
    Several,
    /// Both languages: at or above the loose floor.
    Many,
}

/// One top-level type: a class, or a Rust struct/enum/trait/union. `methods`
/// counts the methods its own body (or its `impl` blocks) define. A type with
/// no methods is a record — a value with a name, not a concept that owns
/// behaviour.
#[derive(Clone, Debug)]
pub struct TypeShape {
    pub name: String,
    pub methods: usize,
}

impl TypeShape {
    fn is_record(&self) -> bool {
        self.methods == 0
    }
}

/// The shape of one module: its top-level classes, the functions it owns, and
/// the functions a framework registered. Only the module body is read — a
/// class's methods are that class's, and a nested class belongs to the class
/// that holds it.
#[derive(Clone, Debug, Default)]
pub struct ModuleShape {
    pub language: Language,
    pub classes: Vec<TypeShape>,
    /// Rust only: free functions grouped by the type their first parameter
    /// takes — a type and the functions that operate on it are one class
    /// equivalent, so the group counts as one definition. A group over a
    /// foreign type (`&Expr`) is one concept too: the helpers around `Expr`.
    pub receiver_groups: Vec<(String, usize)>,
    /// Functions with no receiver type: undecorated (Python) and ungrouped.
    pub functions: usize,
    /// Decorated functions: registered with a caller outside the module.
    pub framework_functions: usize,
    pub generated: bool,
}

/// Measure one module from its parsed body and source text.
pub fn python_module_shape(source: &str, body: &[Stmt]) -> ModuleShape {
    let mut classes = Vec::new();
    let mut functions = 0;
    let mut framework_functions = 0;
    for stmt in body {
        match stmt {
            Stmt::ClassDef(class) => classes.push(TypeShape {
                name: class.name.to_string(),
                methods: class
                    .body
                    .iter()
                    .filter(|member| matches!(member, Stmt::FunctionDef(_)))
                    .count(),
            }),
            Stmt::FunctionDef(function) => {
                if function.decorator_list.is_empty() {
                    functions += 1;
                } else {
                    framework_functions += 1;
                }
            }
            _ => {}
        }
    }
    ModuleShape {
        language: Language::Python,
        classes,
        receiver_groups: Vec::new(),
        functions,
        framework_functions,
        generated: is_generated(source),
    }
}

/// Measure a Rust module from the counts its scan collected: the free `fn`s
/// and the top-level types with the methods their `impl` blocks define. An
/// `impl` block is not a definition of its own — its methods are the type's,
/// exactly as a class's methods are the class's.
pub fn rust_module_shape(
    source: &str,
    functions: usize,
    classes: Vec<TypeShape>,
    receiver_groups: Vec<(String, usize)>,
) -> ModuleShape {
    ModuleShape {
        language: Language::Rust,
        classes,
        receiver_groups,
        functions,
        framework_functions: 0,
        generated: is_generated(source),
    }
}

fn is_generated(source: &str) -> bool {
    source.lines().take(GENERATED_HEAD_LINES).any(|line| {
        let lower = line.to_lowercase();
        GENERATED_MARKERS.iter().any(|marker| lower.contains(marker))
    })
}

fn is_script(rel: &str) -> bool {
    // any directory on the path, not just the first: `src/scripts/x.py` is as
    // much a script as `scripts/x.py`, and the clause exists to answer that
    // reader's objection
    rel.split('/').rev().skip(1).any(|dir| SCRIPT_DIRS.contains(&dir))
}

impl ModuleShape {
    /// The definitions the module holds. Python: classes and undecorated
    /// functions (a constant is a value, not a name; a decorated function is
    /// the framework's entry point). Rust: types, the groups of functions that
    /// take one type (a class equivalent — the type plus its methods in
    /// exile), and the functions left with no receiver.
    pub fn definitions(&self) -> usize {
        self.classes.len() + self.receiver_groups.len() + self.functions
    }

    /// The rung this module sits on, or None when it holds too few definitions
    /// for either. Disjoint by construction: the loose rung is tested first and
    /// its bound is higher, so exactly one rung can match — a module never
    /// reports both. The bounds are stated at [`SEVERAL_MIN`] and [`MANY_MIN`]
    /// (top of this file).
    ///
    fn rung(&self) -> Option<Rung> {
        let count = self.definitions();
        if count >= MANY_MIN {
            return Some(Rung::Many);
        }
        if count >= SEVERAL_MIN {
            return Some(Rung::Several);
        }
        None
    }

    /// The finding for one module, when it holds more than its rung allows.
    pub fn module_finding(&self, rel: &str) -> Option<Finding> {
        if self.generated {
            return None;
        }
        match self.rung()? {
            Rung::Many => self.many_finding(rel),
            Rung::Several => self.several_finding(rel),
        }
    }

    /// What the definitions ARE decides the message: classes become a package,
    /// free functions get the class they are missing. A module of classes and
    /// framework entry points only is a framework contract, not a finding.
    fn many_finding(&self, rel: &str) -> Option<Finding> {
        if self.classes_dominate() {
            Some(self.finding("many-definitions", "warn", rel, self.classes_message(rel)))
        } else if self.functions_are_a_group() {
            Some(self.finding("many-definitions", "warn", rel, self.functions_message(rel, true)))
        } else {
            None
        }
    }

    fn several_finding(&self, rel: &str) -> Option<Finding> {
        if self.classes_dominate() {
            Some(self.finding("several-definitions", "warn", rel, self.classes_message(rel)))
        } else if self.functions_are_a_group() {
            Some(self.finding("several-definitions", "warn", rel, self.functions_message(rel, false)))
        } else {
            None
        }
    }

    /// The functions arm needs a group to make its claim: "the data the
    /// others share" is false of a single helper, and a module of one class
    /// and two helpers is one concept, not several.
    fn functions_are_a_group(&self) -> bool {
        self.functions >= FUNCTIONS_GROUP_MIN
    }

    /// The types arm applies when the owned concepts (types and the function
    /// groups that take one) are the bulk of the definitions AND more than one
    /// of the types carries behaviour. "All but one are records", with no
    /// function groups, is one class plus its value types: one concept, no
    /// finding.
    fn classes_dominate(&self) -> bool {
        // the types arm can only speak for a module that HAS types: a Rust
        // module of function groups and free functions was getting
        // "0 of them types ()" (2026-11-18 review)
        if self.classes.is_empty() {
            return false;
        }
        let owned = self.classes.len() + self.receiver_groups.len();
        owned > self.functions
            && (self.classes.iter().filter(|c| !c.is_record()).count() > 1 || !self.receiver_groups.is_empty())
    }

    fn classes_message(&self, rel: &str) -> String {
        let names: Vec<&str> = self.classes.iter().map(|c| c.name.as_str()).collect();
        format!(
            "'{rel}' holds {count} top-level definitions, {types} of them {noun} ({list}){framework}. {principle} {reader} {merge} {package} {record}",
            count = self.definitions(),
            types = names.len(),
            noun = self.type_noun(),
            list = name_list(&names),
            framework = self.framework_clause(),
            principle = self.principle(),
            reader = self.reader_harm(),
            merge = self.merge_action(),
            package = self.package_action(),
            record = self.record_exclusion(),
        )
    }

    /// The groups, named: a class equivalent is the type plus the functions
    /// that take it, so the groups are what the reader actually holds.
    fn groups_clause(&self) -> String {
        if self.receiver_groups.is_empty() {
            return String::new();
        }
        format!(
            " The functions group by the type they take: {}.",
            group_list(&self.receiver_groups)
        )
    }

    /// The module-shape principle, stated once here and quoted by both arms:
    /// a module holds one concern, and a concern is a class (a Rust class
    /// equivalent is a type plus its impl). The action then depends on which
    /// case the definitions are — one concern, or several — and both arms
    /// write both cases (writing only one would prescribe the wrong fix for
    /// the other).
    fn principle(&self) -> &'static str {
        match self.language {
            Language::Python => "A module holds one concern, and a concern is a class.",
            Language::Rust => "A module holds one concern, and a concern is a type with its impl.",
        }
    }

    /// The one-concern case for the types arm: the classes are the same
    /// concept, so the module keeps one and folds the rest in.
    fn merge_action(&self) -> &'static str {
        match self.language {
            Language::Python => "If the classes are one concern, fold them into the one that owns the state.",
            Language::Rust => "If the types are one concern, fold them into the one that owns the state.",
        }
    }

    /// `many` selects the rung: the loose rung's module is a grab-bag, so its
    /// action leads with the split; the strict rung's module is one concept with
    /// a missing owner, so its action leads with the class.
    fn functions_message(&self, rel: &str, many: bool) -> String {
        let script = if self.language == Language::Python && is_script(rel) {
            " A script is not different: the steps it runs build one program state, and no name owns it."
        } else {
            ""
        };
        format!(
            "'{rel}' holds {count} top-level definitions{breakdown}{framework}. {principle} A free function owns no state, so the data the functions share arrives as parameters and every call site re-states it.{groups}{script} {action}",
            count = self.definitions(),
            breakdown = self.functions_breakdown(),
            framework = self.framework_clause(),
            principle = self.principle(),
            groups = self.groups_clause(),
            script = script,
            action = self.functions_action(many),
        )
    }

    /// Python: "23 of them functions". Rust: "(17 types, 16 function groups,
    /// 65 free functions)" — the class equivalents, so the count is checkable.
    fn functions_breakdown(&self) -> String {
        match self.language {
            Language::Python => format!(", {} of them functions", self.functions),
            Language::Rust => {
                let mut parts = Vec::new();
                if !self.classes.is_empty() {
                    parts.push(counted(self.classes.len(), "type"));
                }
                if !self.receiver_groups.is_empty() {
                    parts.push(counted(self.receiver_groups.len(), "function group"));
                }
                if self.functions > 0 {
                    parts.push(counted(self.functions, "free function"));
                }
                if parts.is_empty() {
                    return String::new();
                }
                format!(" ({})", parts.join(", "))
            }
        }
    }

    fn type_noun(&self) -> &'static str {
        match self.language {
            Language::Python => "classes",
            Language::Rust => "types",
        }
    }

    fn reader_harm(&self) -> &'static str {
        match self.language {
            Language::Python => {
                "A reader looking for one class reads past the rest, and the import path never states which class lives where."
            }
            Language::Rust => {
                "A reader looking for one type reads past the rest, and the module path never states which type lives where."
            }
        }
    }

    fn package_action(&self) -> &'static str {
        match self.language {
            Language::Python => {
                "If they are several, turn the module into a package — one file per class inside it, named after its class and re-exported from __init__.py — so the family keeps its name."
            }
            Language::Rust => {
                "If they are several, turn the module into a directory of modules — one file per type inside it, re-exported from the module root — so the family keeps its name."
            }
        }
    }

    fn functions_action(&self, many: bool) -> &'static str {
        match (self.language, many) {
            (Language::Python, _) => {
                "If the functions are one concern, make them a class: the data becomes its fields and the functions its methods. If they are several, split the module until each concern has its module and its class."
            }
            (Language::Rust, false) => {
                "If the functions are one concern, give them the type they operate on as an impl; a foreign type takes one trait instead. If they are several, split the module by concern, one module per type the functions operate on."
            }
            (Language::Rust, true) => {
                "If the functions are several concerns, split the module by concern: one module per family, each owning the type it introduces. If they are one concern, give them the type they operate on as an impl, keeping the free function where a `&mut` borrow would conflict."
            }
        }
    }

    fn record_exclusion(&self) -> &'static str {
        match self.language {
            Language::Python => "A class with no methods may stay beside the class that uses it.",
            Language::Rust => "A type with no impl may stay beside the type that uses it.",
        }
    }

    /// The framework entry points, named as the rule's own exclusion rather
    /// than silently dropped from the count.
    fn framework_clause(&self) -> String {
        if self.framework_functions == 0 {
            String::new()
        } else {
            format!(
                ", and {} more functions registered with a framework",
                self.framework_functions
            )
        }
    }

    fn finding(&self, kind: &str, severity: &str, rel: &str, message: String) -> Finding {
        Finding {
            logical_start: None,
            seam_members: Vec::new(),
            col: 0,
            file: rel.to_string(),
            line: 0,
            function: String::new(),
            kind: kind.to_string(),
            severity: severity.to_string(),
            message,
        }
    }
}

/// `1 type`, `2 types` — a count with its noun, so a one-item group does not
/// read as "1 function groups".
fn counted(n: usize, noun: &str) -> String {
    if n == 1 {
        format!("1 {noun}")
    } else {
        format!("{n} {noun}s")
    }
}

/// One finding per module that holds more definitions than its rung allows.
pub fn module_findings(scans: &[(String, ModuleShape)]) -> Vec<Finding> {
    scans
        .iter()
        .filter_map(|(rel, shape)| shape.module_finding(rel))
        .collect()
}

fn group_list(groups: &[(String, usize)]) -> String {
    let shown: Vec<String> = groups
        .iter()
        .take(3)
        .map(|(name, count)| format!("{name} ({count})"))
        .collect();
    let list = shown.join(", ");
    match groups.len().saturating_sub(shown.len()) {
        0 => list,
        1 => format!("{list} and one more"),
        more => format!("{list} and {more} more"),
    }
}

fn name_list(names: &[&str]) -> String {
    let shown: Vec<&str> = names.iter().take(3).copied().collect();
    let list = shown.join(", ");
    match names.len().saturating_sub(shown.len()) {
        0 => list,
        1 => format!("{list} and one more"),
        more => format!("{list} and {more} more"),
    }
}
